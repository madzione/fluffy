package main

import (
	"fmt"
	"go/format"
	"go/types"
	"sort"
	"strings"
)

// Generation of golang/fluffy_api.go: the registration of the
// //fluffy:export functions and the Go implementations of the //fluffy:dart
// interfaces. It is nil when there is neither.
func (a *api) generateGo() []byte {
	if len(a.exports) == 0 && len(a.ifaces) == 0 {
		return nil
	}
	im := &goImports{api: a, byPath: map[string]string{}}
	var body strings.Builder

	if len(a.exports) > 0 {
		fluffy := im.use(a.fluffy, "fluffy")
		body.WriteString("func init() {\n")
		for _, e := range a.exports {
			fmt.Fprintf(&body, "\t%s.Export(%q, %s)\n", fluffy, e.channel, im.object(e.fn.Pkg(), e.fn.Name()))
		}
		body.WriteString("}\n")
	}

	for _, d := range a.ifaces {
		code, err := im.iface(d)
		if err != nil {
			a.errorf(d.obj.Pos(), "//fluffy:dart %s: %v", d.obj.Name(), err)
			continue
		}
		body.WriteString("\n" + code)
	}

	var out strings.Builder
	out.WriteString("// Code generated by fluffy generate. DO NOT EDIT.\n\npackage main\n\n")
	if len(im.byPath) > 0 {
		paths := make([]string, 0, len(im.byPath))
		for path := range im.byPath {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		// Standard library first, like goimports. The module of golang/ has
		// no dot in its path either.
		isStd := func(path string) bool {
			return !strings.Contains(strings.Split(path, "/")[0], ".") && !strings.HasPrefix(path+"/", a.module+"/")
		}
		sort.SliceStable(paths, func(i, j int) bool { return isStd(paths[i]) && !isStd(paths[j]) })
		out.WriteString("import (\n")
		for i, path := range paths {
			if i > 0 && isStd(paths[i-1]) && !isStd(path) {
				out.WriteString("\n")
			}
			name := im.byPath[path]
			if name == lastElem(path) {
				fmt.Fprintf(&out, "\t%q\n", path)
			} else {
				fmt.Fprintf(&out, "\t%s %q\n", name, path)
			}
		}
		out.WriteString(")\n\n")
	}
	out.WriteString(body.String())

	src, err := format.Source([]byte(out.String()))
	if err != nil {
		// A bug in the generator, show the source so it can be found.
		a.errorf(0, "generated Go code does not parse: %v\n%s", err, out.String())
		return []byte(out.String())
	}
	return src
}

func lastElem(path string) string {
	return path[strings.LastIndex(path, "/")+1:]
}

// goImports names the packages the generated file imports, avoiding the
// names golang/ already declares.
type goImports struct {
	api    *api
	byPath map[string]string
}

func (im *goImports) use(path, name string) string {
	if have, ok := im.byPath[path]; ok {
		return have
	}
	taken := func(n string) bool {
		if im.api.main != nil && im.api.main.Scope().Lookup(n) != nil {
			return true
		}
		for _, have := range im.byPath {
			if have == n {
				return true
			}
		}
		return false
	}
	alias := name
	for i := 2; taken(alias); i++ {
		alias = fmt.Sprintf("%s%d", name, i)
	}
	im.byPath[path] = alias
	return alias
}

func (im *goImports) qualifier(p *types.Package) string {
	if p.Path() == im.api.module {
		return ""
	}
	return im.use(p.Path(), p.Name())
}

func (im *goImports) object(pkg *types.Package, name string) string {
	if q := im.qualifier(pkg); q != "" {
		return q + "." + name
	}
	return name
}

func (im *goImports) iface(d *dartIface) (string, error) {
	iface := d.obj.Type().Underlying().(*types.Interface)
	for i := 0; i < iface.NumMethods(); i++ {
		if err := im.api.nameable(iface.Method(i).Type()); err != nil {
			return "", fmt.Errorf("%s: %w", iface.Method(i).Name(), err)
		}
	}

	impl := "fluffy" + d.class
	fluffy := im.use(im.api.fluffy, "fluffy")
	var b strings.Builder
	fmt.Fprintf(&b, "// %s returns a %s that forwards every call to the Dart implementation\n// registered with %s.register (lib/golang/api.g.dart).\n", d.ctor, d.obj.Name(), d.class)
	fmt.Fprintf(&b, "func %s() %s {\n\treturn %s{}\n}\n\n", d.ctor, im.object(d.obj.Pkg(), d.obj.Name()), impl)
	fmt.Fprintf(&b, "type %s struct{}\n", impl)

	for i := 0; i < iface.NumMethods(); i++ {
		fn := iface.Method(i)
		sig := fn.Signature()
		var params, args []string
		ctx := ""
		for j := 0; j < sig.Params().Len(); j++ {
			t := types.TypeString(sig.Params().At(j).Type(), im.qualifier)
			if j == 0 && isContext(sig.Params().At(j).Type()) {
				params = append(params, "ctx "+t)
				ctx = "ctx"
				continue
			}
			name := fmt.Sprintf("p%d", len(args)+1)
			params = append(params, name+" "+t)
			args = append(args, name)
		}
		var results []string
		for j := 0; j < sig.Results().Len(); j++ {
			results = append(results, types.TypeString(sig.Results().At(j).Type(), im.qualifier))
		}
		resultList := strings.Join(results, ", ")
		if len(results) > 1 {
			resultList = "(" + resultList + ")"
		}
		if ctx == "" && len(results) > 0 {
			// Only requests wait, emits do not need a context.
			ctx = im.use("context", "context") + ".Background()"
		}
		channel := fmt.Sprintf("%q", d.prefix+"."+fn.Name())
		data := "[]any{" + strings.Join(args, ", ") + "}"

		fmt.Fprintf(&b, "\nfunc (%s) %s(%s) %s {\n", impl, fn.Name(), strings.Join(params, ", "), resultList)
		switch len(results) {
		case 0:
			fmt.Fprintf(&b, "\tif err := %s.Emit(%s, %s); err != nil {\n\t\t%s.Printf(\"fluffy: %%v\", err)\n\t}\n",
				fluffy, channel, data, im.use("log", "log"))
		case 1:
			fmt.Fprintf(&b, "\t_, err := %s.Request[any](%s, %s, %s)\n\treturn err\n", fluffy, ctx, channel, data)
		default:
			fmt.Fprintf(&b, "\treturn %s.Request[%s](%s, %s, %s)\n", fluffy, results[0], ctx, channel, data)
		}
		b.WriteString("}\n")
	}
	return b.String(), nil
}

// nameable reports an error if golang/ cannot refer to a type, because it
// is unexported in another package.
func (a *api) nameable(t types.Type) error {
	seen := map[types.Type]bool{}
	var check func(t types.Type) error
	check = func(t types.Type) error {
		if seen[t] {
			return nil
		}
		seen[t] = true
		switch t := types.Unalias(t).(type) {
		case *types.Named:
			obj := t.Obj()
			if obj.Pkg() != nil && obj.Pkg().Path() != a.module && !obj.Exported() {
				return fmt.Errorf("the type %s is not exported", types.TypeString(t, shortQualifier))
			}
			if args := t.TypeArgs(); args != nil {
				for i := 0; i < args.Len(); i++ {
					if err := check(args.At(i)); err != nil {
						return err
					}
				}
			}
		case *types.Pointer:
			return check(t.Elem())
		case *types.Slice:
			return check(t.Elem())
		case *types.Array:
			return check(t.Elem())
		case *types.Chan:
			return check(t.Elem())
		case *types.Map:
			if err := check(t.Key()); err != nil {
				return err
			}
			return check(t.Elem())
		case *types.Signature:
			for _, tuple := range []*types.Tuple{t.Params(), t.Results()} {
				for i := 0; i < tuple.Len(); i++ {
					if err := check(tuple.At(i).Type()); err != nil {
						return err
					}
				}
			}
		}
		return nil
	}
	return check(t)
}
